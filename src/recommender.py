"""Reusable search and nearest-neighbor recommendation functions."""
from __future__ import annotations
from pathlib import Path
from typing import Any
import joblib
import numpy as np
import pandas as pd

AUDIO_FEATURES = [
    "danceability", "energy", "loudness", "speechiness", "acousticness",
    "instrumentalness", "liveness", "valence", "tempo",
]
FEATURE_LABELS = {
    "danceability": "Danceability", "energy": "Energy", "loudness": "Loudness",
    "speechiness": "Speechiness", "acousticness": "Acousticness",
    "instrumentalness": "Instrumentalness", "liveness": "Liveness",
    "valence": "Valence", "tempo": "Tempo",
}


def load_artifacts(models_dir: str | Path = "models") -> dict[str, Any]:
    """Load artifacts generated by train_model.py and validate their dimensions."""
    path = Path(models_dir)
    required = {
        "songs": path / "songs.csv",
        "scaled_features": path / "X_scaled.npy",
        "neighbor_model": path / "nearest_neighbors.joblib",
    }
    missing = [str(p) for p in required.values() if not p.is_file()]
    if missing:
        raise FileNotFoundError(
            "Model artifacts are missing. Run `python train_model.py` first. Missing: "
            + ", ".join(missing)
        )

    songs = pd.read_csv(required["songs"]).reset_index(drop=True)
    scaled = np.load(required["scaled_features"])
    model = joblib.load(required["neighbor_model"])
    if len(songs) != len(scaled):
        raise ValueError("The saved metadata and feature matrix have different row counts.")
    if scaled.ndim != 2 or scaled.shape[1] != len(AUDIO_FEATURES):
        raise ValueError("The saved feature matrix has an unexpected shape.")
    return {"songs": songs, "scaled_features": scaled, "neighbor_model": model}


def search_songs(songs: pd.DataFrame, query: str, limit: int = 30) -> pd.DataFrame:
    """Search track titles and artists with literal, case-insensitive matching."""
    if not isinstance(query, str) or not query.strip():
        return songs.iloc[0:0].copy()
    q = query.strip()
    title_match = songs["name"].astype(str).str.contains(q, case=False, na=False, regex=False)
    artist_match = songs["artists"].astype(str).str.contains(q, case=False, na=False, regex=False)
    return songs.loc[title_match | artist_match].head(max(1, int(limit))).copy()


def recommend_by_index(
    track_index: int,
    songs: pd.DataFrame,
    scaled_features: np.ndarray,
    neighbor_model: Any,
    top_n: int = 10,
    exclude_same_artist: bool = False,
) -> pd.DataFrame:
    """Retrieve nearest tracks by Euclidean distance in standardized feature space.

    A lower feature distance means closer numeric audio-feature vectors. It is not
    a probability, accuracy percentage, or a guarantee of listener preference.
    """
    if not isinstance(track_index, (int, np.integer)) or not 0 <= int(track_index) < len(songs):
        raise IndexError("The selected track index is outside the available dataset.")
    if len(songs) < 2:
        return pd.DataFrame(columns=["name", "artists", "spotify_id", "feature_distance"])

    top_n = max(1, min(int(top_n), len(songs) - 1))
    request_count = len(songs) if exclude_same_artist else min(len(songs), top_n + 1)
    query = scaled_features[int(track_index)].reshape(1, -1)
    distances, indices = neighbor_model.kneighbors(query, n_neighbors=request_count)

    target_artist = str(songs.iloc[int(track_index)]["artists"])
    rows: list[dict[str, Any]] = []
    seen_display_records: set[tuple[str, str]] = set()
    for distance, candidate_idx in zip(distances[0], indices[0]):
        candidate_idx = int(candidate_idx)
        if candidate_idx == int(track_index):
            continue
        candidate = songs.iloc[candidate_idx]
        if exclude_same_artist and str(candidate["artists"]) == target_artist:
            continue
        spotify_id = candidate.get("spotify_id")
        rows.append({
            "name": str(candidate["name"]),
            "artists": str(candidate["artists"]),
            "spotify_id": None if pd.isna(spotify_id) else str(spotify_id),
            "feature_distance": float(distance),
        })
        if len(rows) >= top_n:
            break
    return pd.DataFrame(rows, columns=["name", "artists", "spotify_id", "feature_distance"])


def closest_feature_dimensions(
    target_scaled: np.ndarray,
    candidate_scaled: np.ndarray,
    top_k: int = 3,
) -> list[str]:
    """Return feature labels with the smallest standardized per-feature gaps."""
    gaps = np.abs(np.asarray(target_scaled) - np.asarray(candidate_scaled)).reshape(-1)
    if len(gaps) == 0 or len(gaps) > len(AUDIO_FEATURES):
        return []
    available_features = AUDIO_FEATURES[:len(gaps)]
    order = np.argsort(gaps)[:max(1, min(int(top_k), len(available_features)))]
    return [FEATURE_LABELS[available_features[int(i)]] for i in order]
